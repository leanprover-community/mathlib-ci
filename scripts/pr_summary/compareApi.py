#!/usr/bin/env python3
"""compareApi.py — compare two API dumps written by `dumpReasonableDecls.lean` and
classify every difference between them.

Each difference between the public API at a PR's merge base and at its head goes into one
*class* (`CLASSES`): removed while deprecated, newly deprecated, moved to another module,
attributes changed, and so on. The classes present make up the PR's *shape*: "deprecations",
"additions", "moves", or a mix. Some differences are worth a reviewer's attention whatever
the shape, such as a declaration removed with no deprecation: their items carry a warning.

Nothing calls this yet. It prints the classes as JSON, for trying it on real dumps.

What is compared is what the dumps record (`dumpReasonableDecls.lean`, *The API dump*):
names, kinds, modules, deprecations, aliases, attributes, docstrings, `protected`, and
whether a declaration was generated by an attribute (`to_additive`, `to_dual`, `simps`, …).
Statements are not in the dumps, so:

* a renamed declaration reads as one removed and one added. Hence "removed or renamed";
* a new deprecation is not checked to state what the name stated before.

What Lean makes for an inductive type (`rec`, `casesOn`, a constructor's `injEq`, …) goes
with it: when a structure becomes an abbreviation, they are listed under its change of kind,
not as removals.

Two dumps are compared only on the fields both headers list at the same version
(`apiDump.comparable_fields`). A field that is not compared reads as unchanged, so its class
stays empty. Two warnings need more than that, since they say what a declaration was *not*:
a removal is flagged only when deprecations (`dep`) and names realised on demand (`rs`) are
compared, and a deleted module only when module deprecations (`dm`) are.

The dumps come from a PR's own build, so they are untrusted: a value of the wrong type
raises `ApiDumpError`, and no message quotes the file. Names and notes in the result are the
dumps' own strings, for whoever renders them to escape.

Usage:
  compareApi.py BASE HEAD [--date YYYY-MM-DD] [--cutoff YYYY-MM-DD]

`BASE` and `HEAD` are `api.jsonl` files or dump directories. `--date` is the PR's date: a
new deprecation's `since` after it is flagged. `--cutoff` is the date up to which deprecated
declarations may be removed: removing one deprecated after it is flagged.
"""

from __future__ import annotations

import argparse
import datetime
import json
import re
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from apiDump import API_FILE, NEVER_COMPARED, ApiDump, ApiDumpError, comparable_fields, read_api

# A deprecation dated more than this many days before the PR is worth a note: deprecated
# declarations are removed by their `since` date, so an old date shortens the time they last.
STALE_SINCE_DAYS = 30


# ---------------------------------------------------------------------------- rows
#
# `check_rows` leaves in each row only the fields compared, each with a value of the right
# type that is not its empty one (`apiDump.EMPTY`). So below, `row.get(f)` is the field's
# value or `None`, and for the two list fields `row.get(f, ())`: a field left out by the
# dumper as empty, written out as empty, or not compared reads the same on both sides.


def _is_strings(v) -> bool:
    return isinstance(v, list) and all(isinstance(x, str) for x in v)


def _is_record(*keys: str):
    """A JSON object with exactly these keys, each a string or null."""
    def check(v) -> bool:
        return (isinstance(v, dict) and set(v) == set(keys)
                and all(x is None or isinstance(x, str) for x in v.values()))
    return check


def _is_alias(v) -> bool:
    return (isinstance(v, dict) and set(v) == {"k", "of"} and isinstance(v["k"], str)
            and v["k"] in ALIAS_ARROWS and isinstance(v["of"], str))


ALIAS_ARROWS = {"plain": "→", "forward": "→ (.mp)", "reverse": "→ (.mpr)"}

# What a value of each field must be, once it is not the field's empty value.
_CHECKS = {
    "k": lambda v: isinstance(v, str),
    "m": lambda v: isinstance(v, str),
    "d": lambda v: isinstance(v, str),
    "a": _is_strings,
    "p": lambda v: v is True,
    "x": lambda v: isinstance(v, str),
    "g": lambda v: v is True,
    "dep": _is_record("to", "since", "text"),
    "al": _is_alias,
    "rs": lambda v: v is True,
    "l": lambda v: type(v) is int,
    "dm": _is_record("since", "text"),
    "md": lambda v: isinstance(v, str),
    "imp": _is_strings,
    "src": lambda v: isinstance(v, str),
}

# The keys, and where a declaration or module is, for links: kept whatever is compared.
_KEPT = frozenset({"n", "mod"}) | NEVER_COMPARED


def check_rows(rows: dict[str, dict], fields: frozenset[str]) -> None:
    """Reduce every row, in place, to the fields in `fields` and `_KEPT` that this script
    knows, dropping empty values. Raises `ApiDumpError` for a value of the wrong type."""
    for row in rows.values():
        for key in list(row):
            v = row[key]
            if key in ("n", "mod"):
                continue
            check = _CHECKS.get(key)
            if (check is None or (key not in fields and key not in _KEPT)
                    or v is None or v is False or v == []):
                del row[key]
            elif not check(v):
                raise ApiDumpError(f"a row's `{key}` is not what that field holds")


# ------------------------------------------------------------------- the delta


@dataclass
class Item:
    """One difference: a declaration or a module, and what to say about it."""

    name: str
    note: str = ""
    warn: str = ""   # non-empty: a reviewer should look at this whatever the shape
    since: str = ""  # the deprecation date, where one is involved
    refs: list = field(default_factory=list)  # the names that `note` and `warn` mention
    copies: list = field(default_factory=list)  # translations with the same change (`fold_copies`)
    dsimp: list = field(default_factory=list)  # lemmas named after it now used by `dsimp`
    # what Lean made for it as an inductive type, gone or new with its change of kind
    # (`kinds_changed`): for a full report, not for the comment
    made_by_lean: list = field(default_factory=list)


# key -> (heading, shape component). A component of None marks noise: listed, never shaped.
CLASSES = {
    "removed":         ("removed or renamed without deprecation", "removals"),
    "dep-renamed":     ("deprecated alias renamed", "removals"),
    "mod-removed":     ("modules deleted without `deprecated_module`", "removals"),
    "now-hand-written": ("were generated by an attribute, now hand-written", "now hand-written"),
    "deprecated":      ("newly deprecated", "deprecations"),
    "dep-retargeted":  ("older deprecations re-pointed", "deprecations"),
    # A plain alias is not a deprecation, so it shapes a PR apart: re-pointing one alone is not
    # "deprecations", and a rename PR that does it reads "deprecations + alias changes".
    "alias-retargeted": ("aliases re-pointed", "alias changes"),
    "undeprecated":    ("deprecation withdrawn", "deprecations"),
    "mod-deprecated":  ("modules newly deprecated", "deprecations"),
    "dep-removed":     ("removed, were deprecated", "deprecation removal"),
    "mod-dep-removed": ("deprecated modules deleted", "deprecation removal"),
    "added":           ("new declarations", "additions"),
    "mod-added":       ("new modules", "additions"),
    "mod-split":       ("new modules made of moved declarations", "moves"),
    "moved":           ("moved to another module", "moves"),
    "kind":            ("kind changed", "kind changes"),
    "attrs":           ("attributes changed", "attribute changes"),
    "doc":             ("docstrings changed", "docstring changes"),
    "mod-doc":         ("module docstrings changed", "docstring changes"),
    "visibility":      ("`protected` changed", "visibility changes"),
    "now-generated":   ("were hand-written, now generated by an attribute", "now generated"),
    "aux":             ("auxiliary declarations realised on demand", None),
}

# Shape components, in the order the shape names them.
COMPONENTS = [
    "removals", "now hand-written", "deprecations", "alias changes", "deprecation removal",
    "additions", "moves", "kind changes", "attribute changes", "docstring changes",
    "visibility changes", "now generated",
]


@dataclass
class Delta:
    """Every difference between two dumps, by class."""

    base: dict
    head: dict
    # Module rows, by module.
    bmods: dict = field(default_factory=dict)
    hmods: dict = field(default_factory=dict)
    # The fields the two dumps were compared on.
    fields: frozenset = frozenset()
    items: dict = field(default_factory=lambda: defaultdict(list))
    folded: dict = field(default_factory=dict)  # name -> its sub-declarations, listed under it

    def add(self, cls: str, item: Item) -> None:
        self.items[cls].append(item)

    def has(self, *names: str) -> bool:
        """Were the two dumps compared on all of `names`?"""
        return all(n in self.fields for n in names)

    def title(self, cls: str) -> str:
        """The class's heading, for the fields compared."""
        if cls == "removed" and not self.has(*REMOVAL_FIELDS):
            return "removed or renamed"
        if cls == "mod-removed" and not self.has(*MODULE_REMOVAL_FIELDS):
            return "modules deleted"
        return CLASSES[cls][0]

    def warnings(self) -> list[tuple[str, Item]]:
        return [(c, it) for c in CLASSES for it in self.items.get(c, []) if it.warn]

    def components(self) -> list[str]:
        present = {CLASSES[c][1] for c, its in self.items.items() if its}
        return [c for c in COMPONENTS if c in present]

    def shape(self) -> str:
        comps = self.components()
        if not comps:
            return "no API change"
        return comps[0] if len(comps) == 1 else "mixed: " + " + ".join(comps)


# What must be compared to say that a removed declaration had no deprecation and was no
# auxiliary declaration, and that a deleted module had no `deprecated_module`.
REMOVAL_FIELDS = ("dep", "rs")
MODULE_REMOVAL_FIELDS = ("dm",)


# --------------------------------------------------------------------- helpers


def parse_date(s: str | None) -> datetime.date | None:
    try:
        return datetime.date.fromisoformat(s) if s else None
    except ValueError:
        return None


def dep_target(row: dict) -> str | None:
    """Where a deprecated declaration points: its alias target, else its deprecation's."""
    d = row.get("dep")
    return ((row.get("al") or {}).get("of") or d["to"]) if d else None


def short(name: str) -> str:
    """The last component: `Foo.Bar.baz` → `baz`."""
    return name.rsplit(".", 1)[-1]


def namespace(name: str) -> str:
    """All but the last component: `Foo.Bar.baz` → `Foo.Bar`, and `baz` → ``."""
    return name.rsplit(".", 1)[0] if "." in name else ""


def ancestor_in(name: str, names: set) -> str | None:
    """The nearest proper prefix of `name` that is in `names`: `Foo.mk` belongs to `Foo`."""
    p = name
    while "." in p:
        p = p.rsplit(".", 1)[0]
        if p in names:
            return p
    return None


KIND_WORDS = {"ax": "an axiom", "def": "a definition", "thm": "a theorem",
              "opaq": "an opaque definition", "quot": "a quotient primitive",
              "ind": "an inductive type", "ctor": "a constructor", "rec": "a recursor"}

# The names Lean makes for an inductive type `I`, as `I.rec`, and for each of its constructors
# `I.c`, as `I.c.inj`: every suffix that hangs off an inductive type or a constructor in all of
# Mathlib (at mathlib4 `d3b6d8f438c`) and is never written by hand. A nested inductive type
# adds `rec_1`, `below_1`, ….
INDUCTIVE_MADE = frozenset({"rec", "recOn", "casesOn", "below", "brecOn", "noConfusion",
                            "noConfusionType", "ctorIdx", "ctorElim", "ctorElimType"})
NESTED_MADE = re.compile(r"(?:rec|below|brecOn)_\d+")
CONSTRUCTOR_MADE = frozenset({"inj", "injEq", "hinj", "noConfusion", "sizeOf_spec", "elim"})


def made_for(name: str, side: dict) -> str | None:
    """The inductive type on `side` that Lean made `name` for, if it did: `Foo` for `Foo.rec`
    and for `Foo.mk.injEq`."""
    p, s = namespace(name), short(name)
    k = side.get(p, {}).get("k")
    if k == "ind" and (s in INDUCTIVE_MADE or NESTED_MADE.fullmatch(s)):
        return p
    if k == "ctor" and s in CONSTRUCTOR_MADE and side.get(namespace(p), {}).get("k") == "ind":
        return namespace(p)
    return None


def kind_changed(base: dict, head: dict, n: str) -> bool:
    return n in base and n in head and base[n].get("k") != head[n].get("k")


def kinds_changed(base: dict, head: dict, removed: set, added: set) -> dict:
    """The names Lean made for an inductive type that is one on one side only, by that type.
    A structure made an abbreviation loses its `rec`, `casesOn`, … and its constructor's
    `inj`, …, which no one writes: they go with its change of kind (`kind_change`), and are
    neither removals nor additions. mathlib4 `d3b6d8f438c` made
    `NumberField.InfinitePlace.Completion` an abbreviation, and lost 10 names so."""
    made = defaultdict(list)
    for names, side in ((removed, base), (added, head)):
        for n in sorted(names):
            i = made_for(n, side)
            if i and kind_changed(base, head, i):
                made[i].append(n)
    return dict(made)


def is_instance(row: dict) -> bool:
    return any(a.startswith("instance:") for a in row.get("a", ()))


# Attributes whose tag carries a parameter (`instance:PRIO`, `reducibility:[LEVEL]`): a change
# of parameter is one change, not an attribute added and another removed.
PARAMETERISED_ATTRS = ("instance", "reducibility")

DSIMP_GAINED = "now used by `dsimp`"
DSIMP_LOST = "no longer used by `dsimp`"
# A `simp` lemma that loses `defeq` stays in the simp set, so nothing fails: `dsimp` calls that
# used it just stop rewriting with it.
DSIMP_LOST_WARNING = ("no longer used by `dsimp`, though still `simp`: `dsimp` calls that "
                      "rewrote with it stop doing so, silently")


def describe_attrs(before: list[str], after: list[str]) -> str:
    """What changed between two attribute lists, in words where a tag carries a parameter:
    "instance priority 1000 → 90", "reducibility reducible → semireducible". Other attributes
    read `+simp −ext`.

    Only global instances are recorded, so losing `instance` may also mean the instance became
    `scoped`; and `semireducible` is the level a declaration has when no tag is recorded.
    `defeq`, the tag `dsimp` reads, is "now used by `dsimp`" or "no longer used by `dsimp`"."""
    def split(tags: list[str]) -> tuple[dict, set]:
        params, plain = {}, set()
        for t in tags:
            kind, sep, p = t.partition(":")
            if sep and kind in PARAMETERISED_ATTRS:
                params[kind] = p.strip("[]")
            else:
                plain.add(t)
        return params, plain

    (bp, bs), (hp, hs) = split(before), split(after)
    out = []
    bi, hi = bp.get("instance"), hp.get("instance")
    if bi and hi and bi != hi:
        out.append(f"instance priority {bi} → {hi}")
    elif hi and not bi:
        out.append("now a global instance" + (f", priority {hi}" if hi != "1000" else ""))
    elif bi and not hi:
        out.append("no longer a global instance")
    br, hr = bp.get("reducibility", "semireducible"), hp.get("reducibility", "semireducible")
    if br != hr:
        out.append(f"reducibility {br} → {hr}")
    dsimp = DSIMP_GAINED if "defeq" in hs - bs else DSIMP_LOST if "defeq" in bs - hs else ""
    bs, hs = bs - {"defeq"}, hs - {"defeq"}
    tags = [f"+{a}" for a in sorted(hs - bs)] + [f"−{a}" for a in sorted(bs - hs)]
    if tags:
        out.append(" ".join(tags))
    if dsimp:
        out.append(dsimp)
    return "; ".join(out)


def check_since(dep: dict, date: datetime.date | None, item: Item) -> None:
    """Flag a new deprecation's `since` that is missing, malformed or after the PR's date,
    unless the item is flagged already; note one long before it."""
    since = dep["since"]
    if not since:
        item.warn = item.warn or "no `since` date"
        return
    d = parse_date(since)
    if d is None:
        item.warn = item.warn or "malformed `since` date"
        return
    if date is None:
        return
    if d > date:
        item.warn = item.warn or f"`since` {since} is after the PR's date {date}"
    elif (date - d).days > STALE_SINCE_DAYS:
        item.note += f"; `since` is {(date - d).days} days before the PR"


# ------------------------------------------------------------------ the passes
#
# `compare` runs the passes below in the order they are written. Each explains some of the
# names that differ and leaves the rest to the passes after it, so the order is part of what
# they say: a removed name is a deprecated alias renamed before it is a removal. What one
# pass leaves for the next is in `Work`, and each pass's docstring names the classes it adds
# to.


@dataclass
class Work:
    """What the passes of `compare` share. The first block is set once, before any pass; a
    pass fills in or narrows the second, and reads only what the passes before it left."""

    delta: Delta
    date: datetime.date | None
    cutoff: datetime.date | None
    removed: set  # names at the base only
    added: set    # names at the head only
    newly: set    # names on both sides that are deprecated at the head only
    # inductive type -> what Lean made for it, gone or new with its change of kind
    # (`kinds_changed`), which are in neither `removed` nor `added`
    made: dict

    # added names that a new deprecation explains: its target, and the target's translations
    # and sub-declarations (`new_deprecations`)
    accounted: set = field(default_factory=set)
    # removed deprecated name -> the new deprecated name it became (`pair_renamed_deprecations`)
    dep_renamed: dict = field(default_factory=dict)
    # removed names that no pass has explained yet, sorted (from `explained_removals`)
    unexplained: list = field(default_factory=list)
    # added names that no pass has explained yet (from `explained_removals`)
    unmatched: set = field(default_factory=set)

    @property
    def base(self) -> dict:
        return self.delta.base

    @property
    def head(self) -> dict:
        return self.delta.head


def compare(base: ApiDump, head: ApiDump, date: datetime.date | None = None,
            cutoff: datetime.date | None = None) -> Delta:
    """Classify every difference between two dumps, on the fields both have at the same
    version. The dumps' rows are reduced to those fields in place (`check_rows`)."""
    fields = frozenset(comparable_fields(base, head))
    for rows in (base.decls, head.decls, base.modules, head.modules):
        check_rows(rows, fields)
    delta = Delta(base.decls, head.decls, base.modules, head.modules, fields)
    bn, hn = set(delta.base), set(delta.head)
    made = kinds_changed(delta.base, delta.head, bn - hn, hn - bn)
    gone = {n for ns in made.values() for n in ns}
    w = Work(delta, date, cutoff, removed=bn - hn - gone, added=hn - bn - gone,
             newly={n for n in bn & hn
                    if not delta.base[n].get("dep") and delta.head[n].get("dep")},
             made=made)
    # Deprecations first: they explain both removals (none) and additions (the targets).
    new_deprecations(w)
    pair_renamed_deprecations(w)
    explained_removals(w)
    removals(w)
    additions(w)
    surviving_names(w)
    modules(w)
    fold_dsimp_gains(delta)
    fold_copies(delta)
    return delta


# -- names that gained a deprecation


def new_deprecations(w: Work) -> None:
    """A name on both sides, deprecated at the head only: `deprecated`, with everything about
    the name reported there, so `surviving_names` skips it. Fills `accounted`."""
    for n in sorted(w.newly):
        it = new_deprecation(w, n)
        it.made_by_lean = w.made.get(n, [])  # a structure kept as a deprecated alias
        w.delta.add("deprecated", it)
    # Translations and sub-declarations of a new name come with it.
    for a in sorted(w.added):
        if w.head[a].get("x") in w.accounted or ancestor_in(a, w.accounted):
            w.accounted.add(a)


def new_deprecation(w: Work, n: str) -> Item:
    """The item for one newly deprecated name: where it points, then the checks that it
    stands in for the name as it was."""
    b, h = w.base[n], w.head[n]
    dep, al = h["dep"], h.get("al")
    target = al["of"] if al else dep["to"]
    it = Item(n, since=dep["since"] or "", refs=[target] if target else [])
    if al:
        it.note = f"alias {ALIAS_ARROWS[al['k']]} {target}"
    elif target:
        it.note = f"in favour of {target} (not an alias)"
    else:
        text = (dep["text"] or "").strip()
        it.note = (f"no replacement: {text}"
                   if text and text.rstrip(".").lower() != "no replacement" else "no replacement")
    if target and target in w.added:
        it.note += " (new name)"
        w.accounted.add(target)
    elif target and target in w.head:
        it.note += " (existing name)"
    if target and w.head.get(target, {}).get("dep"):
        onward = dep_target(w.head[target])
        it.note += f"; {target} is itself deprecated" + (f" → {onward}" if onward else "")
        if onward:
            it.refs.append(onward)
    if target in w.head and al and al["k"] == "plain":
        t = w.head[target]
        lost = set(b.get("a", ())) - set(t.get("a", ())) - set(h.get("a", ()))
        if lost:
            it.warn = f"attributes not carried over to {target}: {sorted(lost)}"
        elif b.get("d") and not t.get("d"):
            it.warn = f"docstring not carried over to {target}"
    # The deprecated name stands in for the old one, so it should be as visible: dropping
    # `protected` lets `open Foo` bring the short name into scope, where it can clash with
    # a root name. Gaining it is noted only: `@[to_additive] protected alias` makes both
    # copies protected, which is sometimes meant.
    if b.get("p") and not h.get("p"):
        # The line to write; an `alias ⟨_, _⟩` has no one line.
        fix = (f"write `protected alias {short(n)} := {target}`" if al and al["k"] == "plain"
               else "write `protected alias`" if al else "keep it `protected`")
        why = (f"no longer `protected`, so `open {namespace(n)}` now brings `{short(n)}` "
               f"into scope; {fix}")
        it.warn = f"{it.warn}; also {why}" if it.warn else why
    elif h.get("p") and not b.get("p"):
        it.note += "; `protected` now, though the old name was not"
    check_since(dep, w.date, it)
    return it


# -- names that are gone


def pair_renamed_deprecations(w: Work) -> None:
    """Older deprecated aliases renamed. Fills `dep_renamed`, and adds to no class:
    `explained_removals` lists the pairs.

    A rename's find-and-replace also matches deprecated aliases whose own names contain the
    old word, and renames them: mathlib4 #45735 turned `enorm_eq_nnnorm`, deprecated six days
    before, into `eNorm_eq_nnnorm`. The old name, which code may still use, is gone, and the
    new one arrives deprecated. A removed deprecated name is paired with a new deprecated name
    of the same kind that points where it did, or where its target now points."""
    base, head = w.base, w.head
    born = [a for a in sorted(w.added) if head[a].get("dep") and a not in w.accounted]
    taken = set()
    for n in sorted(w.removed):
        b = base[n]
        if not b.get("dep") or b.get("rs"):
            continue
        bt = dep_target(b)
        onward = dep_target(head[bt]) if bt in head else None
        cands = [a for a in born if a not in taken and head[a].get("k") == b.get("k")
                 and dep_target(head[a]) in {bt, onward or bt}]
        if cands:
            since = b["dep"]["since"]
            a = next((a for a in cands if head[a]["dep"]["since"] == since), cands[0])
            w.dep_renamed[n] = a
            taken.add(a)


def explained_removals(w: Work) -> None:
    """The removed names that need no pairing to explain: `aux`, `dep-renamed` and
    `dep-removed`. Sets `unexplained` to the rest, less the sub-declarations of a removed
    declaration, and `unmatched` to the added names that no deprecation explains."""
    base, head, cutoff = w.base, w.head, w.cutoff
    rest = []
    for n in sorted(w.removed):
        r = base[n]
        if r.get("rs"):
            w.delta.add("aux", Item(n, "removed"))
        elif n in w.dep_renamed:
            a, d = w.dep_renamed[n], r["dep"]
            t, hs = dep_target(head[a]), head[a]["dep"]["since"] or ""
            it = Item(n, f"now {a}, deprecated {hs or '(no date)'}" + (f" → {t}" if t else ""),
                      since=hs, refs=[x for x in (a, t) if x])
            since = parse_date(d["since"])
            if cutoff and since and since <= cutoff:
                it.warn = (f"deprecated alias renamed to {a}; deprecated {d['since']}, before the "
                           f"cutoff {cutoff}, so remove {a} rather than restore the old name")
            else:
                it.warn = (f"deprecated alias renamed to {a}, so code using the old name now fails "
                           "instead of warning; keep the old name")
            w.delta.add("dep-renamed", it)
        elif r.get("dep"):
            d = r["dep"]
            it = Item(n, f"deprecated {d['since'] or '(no date)'}"
                         + (f" → {d['to']}" if d["to"] else ""), since=d["since"] or "",
                      refs=[d["to"]] if d["to"] else [])
            since = parse_date(d["since"])
            if cutoff and since and since > cutoff:
                it.warn = f"deprecated {d['since']}, after the cutoff {cutoff}"
            w.delta.add("dep-removed", it)
        else:
            rest.append(n)
    # Sub-declarations of a removed declaration go with it (`Foo.mk` with `Foo`).
    for n in rest:
        p = ancestor_in(n, w.removed)
        if p:
            w.delta.folded.setdefault(p, []).append(n)
        else:
            w.unexplained.append(n)
    renamed_to = set(w.dep_renamed.values())
    w.unmatched = {a for a in w.added
                   if a not in w.accounted and a not in renamed_to and not head[a].get("rs")}


def removals(w: Work) -> None:
    """What is left of the removed names: `removed`. Renamed names are among them, since
    nothing pairs a name with the name that states what it did. Each is flagged, but for:

    * an instance, which is listed: a renamed instance needs no deprecation, and it cannot
      be told from a removed one;
    * every name, when `REMOVAL_FIELDS` are not all compared."""
    base, head = w.base, w.head
    flagged = w.delta.has(*REMOVAL_FIELDS)
    partners = defaultdict(set)  # name -> its translations at the base, in either direction
    for n, r in base.items():
        if r.get("x"):
            partners[n].add(r["x"])
            partners[r["x"]].add(n)
    # Sources that are a head row's new `x`: their attribute makes or names another name now,
    # a new one or one that existed.
    new_sources = {r["x"] for k, r in head.items()
                   if r.get("x") and r["x"] != base.get(k, {}).get("x")}
    for n in w.unexplained:
        if is_instance(base[n]):
            w.delta.add("removed", Item(n, "an instance, removed or renamed"))
            continue
        if not flagged:
            w.delta.add("removed", Item(n))
            continue
        it = Item(n, warn="removed or renamed without a deprecation")
        dep_partners = sorted(p for p in partners.get(n, ()) if head.get(p, {}).get("dep"))
        src = base[n].get("x") if base[n].get("g") else None
        if dep_partners:
            it.warn += f" (its translation {dep_partners[0]} did get one)"
            it.refs = dep_partners[:1]
        elif src in head and not head[src].get("dep") and src not in new_sources:
            # A generated name whose source survives and translates to nothing: the attribute
            # line was deleted. Deleting `@[to_dual (attr := simp)]` reads as this removal and
            # a "−simp" on the source. Only the generated side has the pair's `x`, so a source
            # that still had the attribute would be some head row's new `x`. Which attribute
            # it was, `x` does not say.
            it.warn += (f"; it was generated from {src}, which no longer has the translation "
                        "attribute that made it")
            it.refs = [src]
        w.delta.add("removed", it)


# -- names that are new


def additions(w: Work) -> None:
    """What is left of the added names: `added`, or `deprecated` for one that arrives
    deprecated, and `aux` for a name realised on demand."""
    head = w.head
    for a in sorted(w.unmatched):
        r = head[a]
        p = ancestor_in(a, w.unmatched)
        if p:
            w.delta.folded.setdefault(p, []).append(a)
            continue
        if r.get("dep"):
            # Arrives already deprecated: typically restoring a name an earlier PR removed
            # without an alias.
            d = r["dep"]
            target = dep_target(r)
            note = f"new deprecated alias → {target}" if target else "new, already deprecated"
            it = Item(a, note, since=d["since"] or "", refs=[target] if target else [])
            check_since(d, w.date, it)
            w.delta.add("deprecated", it)
            continue
        gen = r.get("x") and r.get("g")
        w.delta.add("added", Item(a, f"generated from {r['x']}" if gen else "",
                                  refs=[r["x"]] if gen else []))
    for a in sorted(w.added - w.unmatched - w.accounted):
        if head[a].get("rs"):
            w.delta.add("aux", Item(a, "added"))


# -- names on both sides


def surviving_names(w: Work) -> None:
    """A name on both sides, compared field by field: every class not named above. A newly
    deprecated name is skipped, since everything about it is reported on its deprecation."""
    for n in sorted(set(w.base) & set(w.head)):
        if n in w.newly:
            continue
        deprecation_changes(w, n)
        kind_change(w, n)
        other_fields(w, n)


def deprecation_changes(w: Work, n: str) -> None:
    """`undeprecated`, `dep-retargeted` and `alias-retargeted`."""
    b, h = w.base[n], w.head[n]
    bd, hd = b.get("dep"), h.get("dep")
    if bd and not hd:
        w.delta.add("undeprecated", Item(n, f"was deprecated {bd['since'] or '(no date)'}",
                                         warn="deprecation withdrawn"))
    # An alias re-pointed past a name this PR deprecates or removes, as a rename's
    # find-and-replace does: `foo_old → foo` becomes `foo_old → foo_new`.
    retargeted = None  # the class it is listed in
    ba, ha = b.get("al"), h.get("al")
    if bd and hd and dep_target(b) != dep_target(h):
        retargeted, bt, ht = "dep-retargeted", dep_target(b), dep_target(h)
    elif not bd and not hd and ba and ha and ba["of"] != ha["of"]:
        # Not deprecated. Whether its name should have been, as one the rename retires, is
        # a naming call: listed, not flagged.
        retargeted, bt, ht = "alias-retargeted", ba["of"], ha["of"]
    if retargeted:
        why = (", which this PR deprecates" if bt in w.newly else
               ", which this PR removes" if bt in w.removed else "")
        note = (f"now → {ht or 'no replacement'} (was → {bt or 'no replacement'}{why})"
                if retargeted == "dep-retargeted" else f"now alias of {ht} (was of {bt}{why})")
        w.delta.add(retargeted, Item(n, note, refs=[r for r in (ht, bt) if r]))


def kind_change(w: Work, n: str) -> None:
    """`kind`: listed, not flagged, with what Lean made for its old or new kind
    (`kinds_changed`). A constructor whose type changed kind with it is not listed again."""
    bk, hk = w.base[n].get("k"), w.head[n].get("k")
    if bk == hk or ("ctor" in (bk, hk) and kind_changed(w.base, w.head, namespace(n))):
        return
    w.delta.add("kind", Item(n, f"was {KIND_WORDS.get(bk, bk)}, now {KIND_WORDS.get(hk, hk)}",
                             made_by_lean=w.made.get(n, [])))


def other_fields(w: Work, n: str) -> None:
    """A field that is compared for itself: `attrs`, `doc`, `now-generated`,
    `now-hand-written`, `visibility` and `moved`, or `aux` for a name realised on demand that
    moved."""
    b, h = w.base[n], w.head[n]
    ba, ha = b.get("a", ()), h.get("a", ())
    if ba != ha and (note := describe_attrs(ba, ha)):
        lost = "defeq" in ba and "defeq" not in ha and "simp" in ha
        w.delta.add("attrs", Item(n, note, warn=DSIMP_LOST_WARNING if lost else ""))
    # An alias's generated docstring, which names its target and so changes when it is
    # re-pointed, has no `d`: only a docstring someone wrote is compared.
    bd, hd = b.get("d"), h.get("d")
    if bd != hd:
        if hd is None:
            w.delta.add("doc", Item(n, "lost", warn="docstring lost"))
        else:
            w.delta.add("doc", Item(n, "added" if bd is None else "reworded"))
    if not b.get("g") and h.get("g"):
        w.delta.add("now-generated", Item(n))
    if b.get("g") and not h.get("g"):
        w.delta.add("now-hand-written", Item(n))
    if b.get("p") != h.get("p"):
        w.delta.add("visibility", Item(n, "now protected" if h.get("p") else "no longer protected"))
    bm, hm = b.get("m"), h.get("m")
    if bm != hm and b.get("rs") and h.get("rs"):
        # A name realised on demand is made in the first module that needs it, so it follows
        # the proofs that use it, not the source.
        w.delta.add("aux", Item(n, f"realised in {hm} (was {bm})", refs=[hm, bm]))
    elif bm != hm:
        w.delta.add("moved", Item(n, f"{bm} → {hm}", refs=[bm, hm]))


# -- modules


def modules(w: Work) -> None:
    """`mod-dep-removed`, `mod-removed`, `mod-split`, `mod-added`, `mod-deprecated` and
    `mod-doc`. Reads the `moved` and `added` items, so it runs after them. A deleted module is
    flagged only when `MODULE_REMOVAL_FIELDS` are compared."""
    delta, bmods, hmods = w.delta, w.delta.bmods, w.delta.hmods
    flagged = delta.has(*MODULE_REMOVAL_FIELDS)
    for m in sorted(set(bmods) - set(hmods)):
        dm = bmods[m].get("dm")
        if dm:
            delta.add("mod-dep-removed", Item(m, f"deprecated {dm['since'] or '(no date)'}",
                                              since=dm["since"] or ""))
        else:
            delta.add("mod-removed", Item(
                m, warn="module deleted with no `deprecated_module`" if flagged else ""))
    # A new module that only receives moved declarations is the other half of a split.
    moved_into, fresh = defaultdict(int), defaultdict(int)
    for it in delta.items.get("moved", []):
        moved_into[delta.head[it.name].get("m")] += 1
    for it in delta.items.get("added", []):
        fresh[delta.head[it.name].get("m")] += 1
    for m in sorted(set(hmods) - set(bmods)):
        if moved_into[m] and not fresh[m]:
            delta.add("mod-split", Item(m, f"receives {moved_into[m]} moved declarations"))
        else:
            delta.add("mod-added", Item(m))
    for m in sorted(set(bmods) & set(hmods)):
        bdm, hdm = bmods[m].get("dm"), hmods[m].get("dm")
        if hdm and not bdm:
            # Every module imports `Init`; the rest name the replacement.
            imp = list(dict.fromkeys(i for i in hmods[m].get("imp", ()) if i != "Init"))
            it = Item(m, "now imports " + ", ".join(imp) if imp else "",
                      since=hdm["since"] or "", refs=imp)
            check_since(hdm, w.date, it)
            delta.add("mod-deprecated", it)
        if bmods[m].get("md") != hmods[m].get("md"):
            delta.add("mod-doc", Item(m, "lost" if hmods[m].get("md") is None else "changed"))


# -- folding


def fold_dsimp_gains(delta: Delta) -> None:
    """List a lemma that is now used by `dsimp`, and changed in nothing else, under the
    definition it is named after (`opMap_τ₁` under `opMap`) when that definition's reducibility
    changed: making a definition `implicit_reducible` makes its `simps` lemmas `@[defeq]`, and
    mathlib4 #44011 did that to 251 lemmas of 69 definitions. The longest such name wins. A
    loss is never folded."""
    its = delta.items.get("attrs", [])
    owners = {it.name: it for it in its if "reducibility " in it.note}
    if not owners:
        return
    kept = []
    for it in its:
        o = (max((o for o in owners if it.name.startswith(o + "_")), key=len, default=None)
             if it.note == DSIMP_GAINED else None)
        if o:
            owners[o].dsimp.append(it.name)
        else:
            kept.append(it)
    delta.items["attrs"] = kept


def fold_copies(delta: Delta) -> None:
    """List a generated translation (`g`, with `x` its source) whose attributes changed
    exactly as its source's did under the source: `@[to_additive]` copies an instance's
    priority, so lowering one lowers both. A chain of translations folds into its first
    source. A self-dual name, whose `x` is itself, folds into nothing, and so does a
    flagged one."""
    its = {it.name: it for it in delta.items.get("attrs", [])}
    if not its:
        return

    def source(n: str) -> str | None:
        r = delta.head.get(n, {})
        x = r.get("x")
        return (x if r.get("g") and x in its and x != n and not its[n].warn
                and its[x].note == its[n].note else None)

    root = {}
    for n in its:
        seen, p = [n], n
        while (q := source(p)) and q not in seen:
            seen.append(q)
            p = q
        root[n] = n if q else p  # a cycle: fold nothing
    for n, r in root.items():
        if r != n:
            its[r].copies.append(n)
    delta.items["attrs"] = [it for it in delta.items["attrs"] if root[it.name] == it.name]


# ----------------------------------------------------------------------- output


def to_json(delta: Delta) -> dict:
    return {
        "shape": delta.shape(),
        "fields": sorted(delta.fields),
        "declarations": {"base": len(delta.base), "head": len(delta.head)},
        "classes": {c: [{k: v for k, v in vars(it).items() if v}
                        | ({"folded": delta.folded[it.name]} if it.name in delta.folded else {})
                        for it in delta.items[c]]
                    for c in CLASSES if delta.items.get(c)},
    }


def _date(s: str) -> datetime.date:
    d = parse_date(s)
    if d is None:
        raise argparse.ArgumentTypeError("not a date written YYYY-MM-DD")
    return d


def _read(path: Path, side: str) -> ApiDump:
    try:
        return read_api(path / API_FILE if path.is_dir() else path)
    except ApiDumpError as e:
        raise ApiDumpError(f"the {side} dump: {e}") from None


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="compareApi.py", description=__doc__.strip().splitlines()[0])
    p.add_argument("base", type=Path)
    p.add_argument("head", type=Path)
    p.add_argument("--date", type=_date)
    p.add_argument("--cutoff", type=_date)
    args = p.parse_args(argv)
    try:
        delta = compare(_read(args.base, "base"), _read(args.head, "head"), args.date, args.cutoff)
    except ApiDumpError as e:
        print(f"compareApi.py: {e}", file=sys.stderr)
        return 1
    json.dump(to_json(delta), sys.stdout, indent=1, ensure_ascii=False)
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
